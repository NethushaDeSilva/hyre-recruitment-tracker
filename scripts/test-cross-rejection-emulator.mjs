import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { initializeApp as adminApp } from 'firebase-admin/app';
import { getFirestore as adminFirestore } from 'firebase-admin/firestore';
import { initializeApp } from 'firebase/app';
import { getFirestore, connectFirestoreEmulator, doc, updateDoc, serverTimestamp, terminate } from 'firebase/firestore';
import { persistCrossRejection, crossRejectionPatch } from '../src/lib/crossRejection.js';
process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8189';
const projectId = 'demo-hyre-cross';
const endpoint = `http://127.0.0.1:8189/emulator/v1/projects/${projectId}`;
const response = await fetch(`${endpoint}:securityRules`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ rules: { files: [{ name: 'firestore.rules', content: readFileSync('firestore.rules','utf8') }] } }) });
assert.equal(response.ok,true,await response.text());
await fetch(`${endpoint}/databases/(default)/documents`,{method:'DELETE'});
const admin = adminFirestore(adminApp({projectId}));
for (const [uid,role] of [['hr','HR'],['interviewer','Interviewer'],['candidate','Candidate']]) await admin.doc(`users/${uid}`).set({role});
for (const id of ['p1','p2']) await admin.doc(`positions/${id}`).set({title:id});
const source = {id:'source', personId:'same',positionId:'p1', stage:'interview', comments:[],history:[]};
const target = {id:'target', personId:'same',positionId:'p2', stage:'screening', comments:[{text:'Preserve me'}],history:[{type:'apply'}]};
const reset = async () => {await admin.doc('applications/source').set(source); await admin.doc('applications/target').set(target);};
const clients=[];
const client = uid => { const db=getFirestore(initializeApp({projectId,apiKey:'demo'},uid));connectFirestoreEmulator(db,'127.0.0.1',8189,{mockUserToken:{sub:uid,email:`${uid}@example.test`}}); clients.push(db);return db; };
const hr=client('hr'), interviewer=client('interviewer'), candidate=client('candidate');
const options={comment:'Candidate chose the current position.',score:'',actor:{uid:'interviewer',role:'Interviewer',name:'Reviewer'}};
const denied = promise => assert.rejects(promise,e=>e.code==='permission-denied');
try {
 await reset();
 await persistCrossRejection(interviewer,'source','target',options);
 assert.equal((await admin.doc('applications/target').get()).data().stage,'rejected');
 assert.equal((await admin.doc('applications/target').get()).data().comments[1].score,0);
 assert.deepEqual((await admin.doc('applications/source').get()).data(),source);
 await assert.rejects(persistCrossRejection(interviewer,'source','target',options),/changed/);
 await reset();
 await persistCrossRejection(hr,'source','target',{...options,actor:{uid:'hr',role:'HR'}});
 await reset();
 await admin.doc('applications/source').update({stage:'screening'});
 await persistCrossRejection(hr,'source','target',{...options,actor:{uid:'hr',role:'HR'}});
 assert.equal((await admin.doc('applications/source').get()).data().stage,'screening');
 await reset();
 const patch = {...crossRejectionPatch(source,target,options)};
 patch.crossRejection={...patch.crossRejection,committedAt:serverTimestamp()};
 await denied(updateDoc(doc(candidate,'applications','target'),patch));
 await denied(updateDoc(doc(interviewer,'applications','target'),{...patch,personId:'forged'}));
 await denied(updateDoc(doc(interviewer,'applications','target'),{...patch,comments:[{text:'changed'},patch.comments[1]]}));
 await denied(updateDoc(doc(interviewer,'applications','target'),{...patch,stage:'hired'}));
 await admin.doc('applications/source').update({personId:'different'});
 await denied(updateDoc(doc(interviewer,'applications','target'),patch));
 await reset(); await admin.doc('applications/source').update({stage:'rejected'});
 await denied(updateDoc(doc(interviewer,'applications','target'),patch));
 await reset(); await admin.doc('applications/source').update({stage:'applied'});
 await denied(updateDoc(doc(interviewer,'applications','target'),patch));
 await reset();
 await updateDoc(doc(hr,'applications','target'),{stage:'rejected'});
 console.log('PASS cross-rejection permissions, immutable current application, preserved feedback, and ordinary rejection');
} finally {await Promise.all(clients.map(terminate));await admin.terminate();}
